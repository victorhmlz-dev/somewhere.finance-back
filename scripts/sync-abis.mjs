// Copies the events of the launchpad contracts from the compiled artifacts of
// somewhere.finance-contracts into src/launchpad/abi.ts, so the indexer always
// decodes exactly what the contracts emit.
//
//   npm run abi:sync
//
// Run it after changing an event in the contracts (and compiling them).
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const CONTRACTS = [
  'Launchpad',
  'TokenSale',
  'CreatorVesting',
  'LaunchpadV3',
  'TokenSaleV3',
  'CreatorVestingV3',
];
const artifactsDir = new URL(
  '../../somewhere.finance-contracts/artifacts/contracts/',
  import.meta.url,
);
const output = new URL('../src/launchpad/abi.ts', import.meta.url);

const exportName = (contract) =>
  `${contract[0].toLowerCase()}${contract.slice(1)}Events`;

const sections = CONTRACTS.map((contract) => {
  const artifact = JSON.parse(
    readFileSync(new URL(`${contract}.sol/${contract}.json`, artifactsDir), 'utf8'),
  );
  const events = artifact.abi.filter((entry) => entry.type === 'event');
  return `export const ${exportName(contract)} = ${JSON.stringify(events, null, 2)} as const;`;
});

writeFileSync(
  output,
  `// Generated by scripts/sync-abis.mjs from somewhere.finance-contracts.\n// Do not edit by hand: run \`npm run abi:sync\`.\n\n${sections.join('\n\n')}\n`,
);
console.log(`Wrote ${fileURLToPath(output)}`);
